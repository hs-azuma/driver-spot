const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { confirmationUrl } = require('../assets/auth-confirm.js');
const base = 'https://wyxuekjikvflpcmlliwn.supabase.co/auth/v1/verify';
const token = 'a'.repeat(64);
const good = `${base}?token=${token}&type=signup&redirect_to=${encodeURIComponent('https://spodora.com/driver.html')}`;
assert.equal(confirmationUrl('#' + good), good);
assert.ok(confirmationUrl(`${base}?token=${token}&type=signup&redirect_to=${encodeURIComponent('https://hs-azuma.github.io/driver-spot/company-register.html')}`));
for (const bad of ['', '#javascript:alert(1)', good.replace('https:', 'http:'), good.replace('wyxuekjikvflpcmlliwn.supabase.co', 'attacker.example'), good.replace('type=signup', 'type=recovery'), good.replace('type=signup', 'type=signup&type=recovery'), good.replace(token, 'short'), good + '#unexpected', `${base}?token=${token}&type=signup&redirect_to=https://attacker.example`]) assert.equal(confirmationUrl(bad), null);
let clicks, navigated, cleared;
const button = { disabled: true, addEventListener: (name, fn) => { assert.equal(name, 'click'); clicks = fn; } };
const window = { document: { getElementById: id => id === 'confirmEmail' ? button : {} }, location: { hash: '#' + good, pathname: '/auth-confirm.html', replace: url => { navigated = url; } }, history: { replaceState: (_, __, url) => { cleared = url; } } };
vm.runInNewContext(fs.readFileSync(require.resolve('../assets/auth-confirm.js'), 'utf8'), { window, URL });
assert.equal(navigated, undefined, 'Opening or scanning page must not consume confirmation');
assert.equal(cleared, '/auth-confirm.html');
assert.equal(button.disabled, false);
clicks();
assert.equal(navigated, good);
assert.equal(button.disabled, true);
console.log('Confirmation destination validation and explicit-click tests passed.');
