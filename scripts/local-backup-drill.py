"""Synthetic PostgreSQL backup drill; isolated container, no published ports or host mounts.
Not a reconstruction of the application. Requires an already cached postgres:17.6 image.
"""
import json
import shutil
import subprocess
import time
import uuid

IMAGE = 'postgres:17.6'
FIXTURE = """
CREATE TABLE public.restore_fixture(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text NOT NULL);
ALTER TABLE public.restore_fixture ENABLE ROW LEVEL SECURITY;
CREATE POLICY fixture_read ON public.restore_fixture FOR SELECT USING (true);
INSERT INTO public.restore_fixture(label) VALUES ('synthetic-one'),('synthetic-two');
"""
VERIFY = """SELECT json_build_object(
 'rows',(SELECT json_agg(t ORDER BY id) FROM public.restore_fixture t),
 'sequence',(SELECT last_value FROM public.restore_fixture_id_seq),
 'rls',(SELECT relrowsecurity FROM pg_class WHERE oid='public.restore_fixture'::regclass),
 'policies',(SELECT count(*) FROM pg_policies WHERE tablename='restore_fixture'))::text;"""


def main():
    if not shutil.which('docker'):
        print('BLOCKED: Docker is unavailable. No database operation attempted.')
        return 2
    name = 'spodora-drill-' + uuid.uuid4().hex[:12]
    def run(*args, input=None):
        result = subprocess.run(['docker', *args], input=input, text=True,
                                capture_output=True, timeout=60, check=True)
        return result.stdout.strip()
    started = False
    try:
        image_id = run('image', 'inspect', '--format', '{{.Id}}', IMAGE)
        run('run', '--detach', '--pull=never', '--name', name, '--network=none',
            '--tmpfs', '/var/lib/postgresql/data:rw', '--tmpfs', '/tmp:rw',
            '--env', 'POSTGRES_HOST_AUTH_METHOD=trust', IMAGE)
        started = True
        for _ in range(30):
            try:
                run('exec', name, 'pg_isready', '-U', 'postgres')
                break
            except subprocess.CalledProcessError:
                time.sleep(1)
        else:
            raise RuntimeError('PostgreSQL did not become ready')
        for db in ('spodora_fixture_source', 'spodora_fixture_restore'):
            run('exec', name, 'createdb', '-U', 'postgres', db)
        def sql(db, text):
            return run('exec', '-i', name, 'psql', '-X', '-U', 'postgres', '-d', db,
                       '-v', 'ON_ERROR_STOP=1', '-At', input=text)
        sql('spodora_fixture_source', FIXTURE)
        before = json.loads(sql('spodora_fixture_source', VERIFY))
        run('exec', name, 'pg_dump', '-U', 'postgres', '-Fc', '--no-owner',
            '-f', '/tmp/fixture.dump', 'spodora_fixture_source')
        run('exec', name, 'pg_restore', '-U', 'postgres', '--exit-on-error',
            '--single-transaction', '--no-owner', '-d', 'spodora_fixture_restore', '/tmp/fixture.dump')
        after = json.loads(sql('spodora_fixture_restore', VERIFY))
        if before != after or len(after['rows']) != 2 or not after['rls'] or after['policies'] != 1:
            raise RuntimeError('Fixture restore mismatch')
        next_id = sql('spodora_fixture_restore',
                      "INSERT INTO public.restore_fixture(label) VALUES ('synthetic-three') RETURNING id;")
        if next_id.splitlines()[0] != '3':
            raise RuntimeError('Restored identity sequence did not advance correctly')
        print(json.dumps({'status': 'PASS_SYNTHETIC_ONLY', 'image': IMAGE, 'image_id': image_id,
                          'verified': ['rows', 'RLS enabled', 'policy count', 'identity next value'],
                          'application_restore': 'NOT_TESTED'}, indent=2))
        return 0
    except (subprocess.SubprocessError, RuntimeError, OSError) as exc:
        print('BLOCKED_OR_FAILED: ' + type(exc).__name__ + '; no application restore claim.')
        return 2
    finally:
        if started:
            run('rm', '--force', '--volumes', name)


if __name__ == '__main__':
    raise SystemExit(main())
