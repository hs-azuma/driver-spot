CREATE OR REPLACE FUNCTION public.scan_driver_attendance(p_token uuid, p_action text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  c_id bigint;
  d_id bigint;
  a public.applications%rowtype;
begin
  if p_action not in ('in','out') then raise exception '打刻種別が不正です'; end if;
  select id into c_id from public.companies where user_id=auth.uid();
  if c_id is null then raise exception '企業アカウントでログインしてください'; end if;
  select id into d_id from public.drivers where attendance_token=p_token;
  if d_id is null then raise exception '無効なドライバーQRコードです'; end if;

  if p_action='in' then
    select ap.* into a
    from public.applications ap
    join public.jobs j on j.id=ap.job_id
    where ap.driver_id=d_id
      and j.company_id=c_id
      and ap.status='勤務確定'
      and ap.checked_in_at is null
      and j.work_date=(now() at time zone 'Asia/Tokyo')::date
    order by abs(extract(epoch from (((j.work_date + j.start_time) at time zone 'Asia/Tokyo') - now()))), ap.id desc
    limit 1 for update of ap;
    if not found then raise exception '本日この会社で出勤待ちの勤務がありません'; end if;
    update public.applications set checked_in_at=now(),attendance_method='qr' where id=a.id;
    return '出勤を記録しました';
  else
    select ap.* into a
    from public.applications ap
    join public.jobs j on j.id=ap.job_id
    where ap.driver_id=d_id
      and j.company_id=c_id
      and ap.status='勤務確定'
      and ap.checked_in_at is not null
      and ap.checked_out_at is null
    order by ap.checked_in_at desc, ap.id desc
    limit 1 for update of ap;
    if not found then raise exception '退勤待ちの勤務がありません。先に出勤打刻をしてください'; end if;
    update public.applications set checked_out_at=now(),attendance_method='qr',status='勤務完了',completed_at=coalesce(completed_at,now()) where id=a.id;
    return '退勤を記録し、勤務完了にしました';
  end if;
end
